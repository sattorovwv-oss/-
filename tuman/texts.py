def tr(key, lang="tj"):
    return TEXT[key][0 if lang == "ru" else 1]


def status(stage, lang="tj"):
    return STATUSES[stage][0 if lang == "ru" else 1]


def card(parcel, lang="tj", full=True, currency="сомонӣ"):
    ru = lang == "ru"
    lines = ["📦 <b>" + escape(parcel["track"]) + "</b>", ("Статус: " if ru else "Ҳолат: ") + status(parcel["stage"], lang)]
    if full:
        if parcel["weight_g"]:
            lines.append(("⚖️ Вес: " if ru else "⚖️ Вазн: ") + display(parcel["weight_g"] / 1000) + " кг")
        if parcel["price_minor"]:
            lines.append(("💰 Стоимость: " if ru else "💰 Нарх: ") + display(parcel["price_minor"] / 100) + " " + escape(currency))
            lines.append(("✅ Оплачено" if ru else "✅ Пардохт шуд") if parcel["paid"] else ("⏳ Не оплачено" if ru else "⏳ Пардохт нашудааст"))
    return "\n".join(lines)
